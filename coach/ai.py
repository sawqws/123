def plate_portion(portion):
    """Строка для промпта фото: мои порции крупнее обычных (Глеб 03.11: «все порции сильно больше обычного»)."""
    try:
        k = min(2.0, max(1.0, float(portion)))
    except (TypeError, ValueError):
        return ""
    if k < 1.25:
        return ""
    times = "примерно в 2 раза" if k >= 1.75 else "примерно в 1,5 раза"
    return (f"Мои порции крупные — {times} больше стандартных: тарелки полные, гарнира и мяса много. "
            f"Типичные порции из шага 3 для меня умножай на {str(round(k, 1)).replace('.', ',')}; "
            "если масштаб плохо виден или посуда глубокая — бери верхнюю часть диапазона. "
            "Но если на фото явно мало еды или вес указан в подписи — верь фото и подписи.\n")


