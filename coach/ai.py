import threading
import tempfile
import uuid

HERE = os.path.dirname(os.path.abspath(__file__))
WORK = os.path.join(tempfile.gettempdir(), "coach-ai")
# Read нужен только чтобы открыть присланное фото из WORK. Текст на картинке мог бы попросить прочитать чужое
# («открой /etc/coach-bot.env») — системные и чужие папки закрыты (WORK лежит в /tmp, его не трогаем).
SAFE_READ = [f"Read(//{d}/**)" for d in ("root", "etc", "home", "proc", "sys", "var", "opt", "usr", "boot", "dev", "run",
                                         "mnt", "media", "srv")]
NO_TOOLS = ["--disallowedTools", "Bash", "Edit", "Write", "NotebookEdit", "WebFetch", "WebSearch", "Task", "Agent", *SAFE_READ]
# Поиск в интернете — только чату приложения (Глеб 03.11: «найди в интернете», как в Claude Code): WebSearch и WebFetch
# разрешены, всё остальное закрыто так же. Разборы, бот и «Калории» идут с NO_TOOLS.
WEB_TOOLS = ["--allowedTools", "WebSearch", "WebFetch",
             "--disallowedTools", *[t for t in NO_TOOLS[1:] if t not in ("WebFetch", "WebSearch")]]
WEB_TIMEOUT = int(os.environ.get("COACH_WEB_TIMEOUT") or 180)  # поиск + чтение страницы — дольше обычного ответа


def persona():
    with open(os.path.join(HERE, "prompt.md"), encoding="utf-8") as f:
        return f.read()


class AIError(Exception):
    pass


def claude(prompt, image=None, timeout=240, images=None, model=None, effort=None, label=None, web=False):
    """(текст ответа). image — путь к картинке, images — несколько (кадры видео): Claude откроет их инструментом Read.
    label — своя подпись к нескольким фото (иначе — «кадры видео» или «одна еда с разных сторон»).
    web — можно искать в интернете (только чат приложения)."""
    os.makedirs(WORK, exist_ok=True)
    copies = []
    pics = ([image] if image else []) + list(images or [])
    try:
        return _run(prompt, pics, copies, timeout, model, effort, label, web)
    finally:
        for c in copies:  # копии картинок нужны только на время ответа
            try:
                os.remove(c)
            except OSError:
                pass


def _run(prompt, pics, copies, timeout, model=None, effort=None, label=None, web=False):
    tools = []
    if pics:
        for src in pics:
            dst = os.path.join(WORK, f"photo-{uuid.uuid4().hex[:8]}" + (os.path.splitext(src)[1].lower() or ".jpg"))
            shutil.copyfile(src, dst)
            copies.append(dst)
        if len(copies) == 1:
            prompt += f"\n\nФото: {copies[0]} (открой его инструментом Read)."
        elif label:
            prompt += f"\n\n{label}\n" + "\n".join(copies)
        elif model:  # несколько фото одной тарелки (сверху, сбоку)
            prompt += "\n\nФото одной и той же еды с разных сторон (открой каждое инструментом Read):\n" + "\n".join(copies)
        else:
            prompt += "\n\nКадры видео по порядку (открой каждый инструментом Read):\n" + "\n".join(copies)
        tools = ["--allowedTools", "Read", "--max-turns", str(3 + len(copies))]
    deny = NO_TOOLS
    if web and not pics:
        deny = WEB_TOOLS
        timeout = max(timeout, WEB_TIMEOUT)
    cmd = ["claude", "-p", prompt, "--output-format", "json", "--append-system-prompt", persona(), *tools, *deny,
           *(["--model", model] if model else []), *(["--effort", effort] if effort else [])]
    try:
        p = subprocess.run(cmd, cwd=WORK, capture_output=True, text=True, timeout=timeout,
                           stdin=subprocess.DEVNULL)  # иначе claude -p ждёт ввод от pm2 — лишние секунды
    except FileNotFoundError:
        raise AIError("Claude Code не установлен на сервере") from None
    except subprocess.TimeoutExpired:
        raise AIError("Claude долго думает — попробуй ещё раз") from None
    try:
        res = json.loads(p.stdout.strip().splitlines()[-1]) if p.stdout.strip() else {}
    except ValueError:
        res = {}
    if p.returncode != 0 or res.get("is_error") or not res.get("result"):
        log = (p.stderr + p.stdout)[-1500:]
        print("claude ->", p.returncode, log)
        low = log.lower()
        if any(w in low for w in ("login", "api key", "401", "unauthorized", "authenticat")):
            raise AIError("Claude на сервере не вошёл в аккаунт")
        if any(w in low for w in ("rate limit", "usage limit", "limit reached", "429", "overloaded")):
            raise AIError("у Claude закончился лимит, попробуй позже")
        raise AIError("Claude не ответил")
    return res["result"].strip()


# Глеб 03.11: «в этом чате нужно покороче писать — слишком много пишет. Кратко, понятно, чётко».
# Чат приложения по умолчанию — 2–5 коротких строк; длинно — только если он сам просит «подробно».
LONG_RX = re.compile(r"подробн|развернут|распиши|расскажи\s+вс[её]|полностью|пошагов|по\s+шагам|на\s+неделю|план\s+(трениров|питан|на\s)|"
                     r"составь|список\s+(всех|продукт)|объясни\s+подробн", re.I)
BRIEF = ("КРАТКО (главное правило этого чата): 2–5 коротких строк. Без вступлений, без пересказа вопроса, без «отличный вопрос», "
         "без воды и общих слов. Первая строка — сразу ответ. Список — не больше 4 пунктов по одной строке. "
         "Без заключений и «если что — пиши». ")
LONG = ("Он сам попросил подробно — можно полнее (до ~15 строк), но так же без воды: пункты «- …», **жирным** главное. ")
SHORT_LIMIT = (6, 650)  # строк, знаков — мягкий предел ответа чата приложения (trim_answer); «подробно» — LONG_LIMIT
LONG_LIMIT = (18, 2600)
TOPICS = {"skin": ("ТЕМА РАЗГОВОРА: КОЖА (это чат в разделе «Кожа»). Отвечай про кожу и уход, опираясь на его уход, "
                   "заметки и разборы фото лба из ДАННЫХ. Просит поменять уход («убери…», «добавь…», «замени…», "
                   "«поменяй вечерний уход…») — сделай это действием skin_routine.")}


def wants_long(question):
    """Сам попросил развёрнуто («подробно», «распиши», «план на неделю»…)."""
    return bool(LONG_RX.search(question or ""))


def chat_prompt(context, history, question, full=False, assist=False, topic=None):
    """Вопрос в чат — о чём угодно (спорт, сон, еда, кожа, учёба, настроение, быт). full — чат приложения, assist —
    он ещё и делает (ACTIONS), ищет в интернете и передаёт ошибки в ремонт; topic="skin" — чат раздела «Кожа».
    И в боте, и в приложении — коротко (BRIEF); длинно — только если сам просит (wants_long)."""
    talk = "\n".join(("Я: " if m["role"] == "user" else "Форма: ") + m["text"][:1200] for m in history)
    how = BRIEF + (LONG if full and wants_long(question) else "")
    if not full:
        how += "Ответ для чата: 2–5 коротких строк, до ~500 знаков (чат бота). "
    return (f"ДАННЫЕ:\n{context}\n\n" + (f"{TOPICS[topic]}\n\n" if topic in TOPICS else "")
            + (f"НЕДАВНИЙ РАЗГОВОР:\n{talk}\n\n" if talk else "")
            + f"ВОПРОС: {question}\n\nОтветь как личный помощник по правилам из системного промпта. {how}"
            "Опирайся на ДАННЫЕ (цифры, режим, привычки, еду, уход), когда они к месту, и не притягивай их, "
            "если вопрос о другом." + ("\n\n" + ASSIST if assist else ""))


def trim_answer(md, long=False):
    """Мягкий предел длины ответа чата приложения: целые строки, лишнее — по концу предложения, не на полуслове.
    Строка «Источники: …» (после поиска) остаётся. (текст, обрезано ли)."""
    lines_max, chars = LONG_LIMIT if long else SHORT_LIMIT
    rows = [x.rstrip() for x in (md or "").strip().splitlines()]
    src = ""
    for i in range(len(rows) - 1, -1, -1):
        if rows[i].strip().lower().startswith(("источники:", "**источники")):
            src = " ".join(rows[i:]).strip() if i == len(rows) - 1 else "\n".join(r for r in rows[i:] if r.strip())
            rows = rows[:i]
            break
    out, n, cut, kept = [], 0, False, 0
    for r in rows:
        if not r.strip():
            if out and out[-1]:
                out.append("")
            continue
        if kept >= lines_max:
            cut = True
            break
        if n + len(r) > chars:
            room = chars - n
            part = r[:room]
            m = max(part.rfind(". "), part.rfind("! "), part.rfind("? "), part.rfind("; "))
            if m >= 40:  # длинная строка — до конца предложения
                piece = part[:m + 1].rstrip(";")
                out.append(piece + ("**" if piece.count("**") % 2 else ""))
            cut = True
            break
        out.append(r)
        n += len(r) + 1
        kept += 1
    while out and not out[-1]:
        out.pop()
    text = "\n".join(out)
    if not text and rows:  # одна огромная строка без точек — хотя бы её начало по слову
        text = rows[0][:chars].rsplit(" ", 1)[0].rstrip(",;:—- ") + "…"
        cut = True
    return (text + ("\n" + src if src else "")).strip(), cut


def ask(context, history, question, full=False, assist=False, topic=None):
    return claude(chat_prompt(context, history, question, full, assist, topic), web=assist)


