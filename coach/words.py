"""Старые названия показателей в текстах Claude и в сохранённых разборах (Глеб 04.11: «пишется опять запас сил —
чтобы такого больше не писалось»). HRV по-русски — «гибкость пульса» (женский род): прежние «запас сил» и
«отдых нервов» меняем на неё во всех падежах и правим род соседнего слова («был средний» → «была средняя»)."""
import re

_CASES = (  # (старое, новое) — сначала длинные формы
    (r"запас(?:ом)\s+сил", "гибкостью пульса"), (r"запас(?:а|у|е)\s+сил", "гибкости пульса"), (r"запас\s+сил", "гибкость пульса"),
    (r"отдыхом\s+нервов", "гибкостью пульса"), (r"отдыха\s+нервов", "гибкости пульса"), (r"отдыху\s+нервов", "гибкости пульса"),
    (r"отдыхе\s+нервов", "гибкости пульса"), (r"отдых\s+нервов", "гибкость пульса"),
)
_GENDER = {"был": "была", "стал": "стала", "упал": "упала", "вырос": "выросла", "снизился": "снизилась", "вернулся": "вернулась",
           "посчитан": "посчитана", "низкий": "низкая", "высокий": "высокая", "средний": "средняя", "нормальный": "нормальная",
           "хороший": "хорошая", "маленький": "маленькая", "большой": "большая", "обычный": "обычная", "просел": "просела",
           "ниже": "ниже", "выше": "выше"}
_RX = [(re.compile(rf"(?i)\b{a}\b"), b) for a, b in _CASES]
_AFTER = re.compile(r"(?i)(гибкость пульса)((?:\s+[а-яё]+){1,3})")
_BEFORE = re.compile(r"(?i)\b([а-яё]+?)(ий|ый|ой|ым|им|ого|его|ому|ему)(\s+)(гибкость|гибкостью|гибкости)(\s+пульса)")
_ADJ = {  # окончание прилагательного перед словом → женский род в том же падеже
    "гибкость": {"ий": "ая", "ый": "ая", "ой": "ая"}, "гибкостью": {"ым": "ой", "им": "ей"},
    "гибкости": {"ого": "ой", "его": "ей", "ому": "ой", "ему": "ей"}}
_PRON = {"твой": "твоя", "мой": "моя", "этот": "эта", "весь": "вся", "твоим": "твоей", "моим": "моей", "твоего": "твоей", "моего": "моей"}


def _keep_case(src, dst):
    return dst[:1].upper() + dst[1:] if src[:1].isupper() else dst


def fix(text):
    """Текст с «гибкостью пульса» вместо старых названий. Не строка или старого нет — как есть."""
    if not isinstance(text, str) or not re.search(r"(?i)запас\w*\s+сил|отдых\w*\s+нервов", text):
        return text
    for rx, new in _RX:
        text = rx.sub(lambda m, new=new: _keep_case(m.group(0), new), text)
    def after(m):
        ws = re.split(r"(\s+)", m.group(2))
        return m.group(1) + "".join(_keep_case(w, _GENDER[w.lower()]) if w.lower() in _GENDER else w for w in ws)
    text = _AFTER.sub(after, text)

    def before(m):
        word = m.group(1) + m.group(2)
        if word.lower() in _PRON:
            return _keep_case(word, _PRON[word.lower()]) + m.group(3) + m.group(4) + m.group(5)
        end = _ADJ[m.group(4).lower()].get(m.group(2).lower())
        return (m.group(1) + end if end else word) + m.group(3) + m.group(4) + m.group(5)
    text = _BEFORE.sub(before, text)
    return text
